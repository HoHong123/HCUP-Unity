/* =========================================================
 * @Jason - PKH
 * 캐시 하나의 진단 상태를 레지스트리와 캐시가 공유하는 손잡이입니다.
 *
 * 특징 / 지원기능 ::
 * 표시용 라벨과 현재 항목 수를 담습니다. 캐시가 값을 쓰고 레지스트리가 읽습니다.
 * + 레지스트리는 이 손잡이를 강하게 잡고 캐시는 약하게 잡습니다
 *
 * 주의사항 ::
 * 에디터 진단 전용이라 통째로 #if UNITY_EDITOR 로 감쌉니다.
 * 캐시가 GC 된 뒤에도 이 손잡이는 살아남습니다. 그래야 "사라질 때 몇 개를 들고 있었나" 를
 * 사후에 판정할 수 있습니다. 이것이 미폐기 provider 를 잡아내는 유일한 근거입니다.
 * =========================================================
 */

namespace HResource.Cache {
    public sealed class AssetCacheDiagnosticsHandle {
        #region Fields
        /// <summary> 진단 창에 표시할 캐시 식별 문자열 </summary>
        public readonly string Label;

        /// <summary> 캐시가 마지막으로 알린 항목 수. 캐시가 사라져도 이 값은 남는다 </summary>
        public int EntryCount;
        #endregion

        #region 생성자
        public AssetCacheDiagnosticsHandle(string label) {
            Label = label;
        }
        #endregion
    }
}

/* =============================================================================
 *  Dev Log
 * =============================================================================
 * @Jason - PKH 2026.09.04 AssetCacheDiagnosticsHandle 베이스 코드 생성
 *
 * # 목적
 * - provider 를 Dispose 없이 버리면 캐시가 GC 되어 진단 대상에서 사라진다.
 *   누수가 발생한 순간 관측 수단이 함께 증발하는 것이 USR-4 의 본질이었다.
 * - 캐시보다 오래 사는 기록을 따로 두어 "사라질 때 점유가 남아 있었는가" 를 판정한다.
 *
 * # 설계 결정
 * - 레지스트리가 강한 참조로, 캐시가 약한 참조로 잡는 비대칭 구조다.
 *   손잡이는 두 필드짜리라 강하게 잡아도 부담이 없고, 캐시 본체는 여전히 GC 된다.
 *
 * =============================================================================
 */
